-- The stock invariant that matters. `track_and_block` promises the storefront will not oversell;
-- this is the backstop if the FOR UPDATE decrement in the order transaction is ever bypassed by a
-- plain Prisma `update`. It is NOT a substitute for the row lock — a CHECK cannot serialise two
-- concurrent readers — it is what turns a silent negative balance into a loud failed transaction.
ALTER TABLE "product_variants" ADD CONSTRAINT "product_variants_stock_not_negative"
  CHECK ("stock_qty" >= 0);

-- 0 = Sunday .. 6 = Saturday. A seventh day does not exist and an eighth row must not be
-- representable.
ALTER TABLE "opening_hours" ADD CONSTRAINT "opening_hours_weekday_range"
  CHECK ("weekday" >= 0 AND "weekday" <= 6);

-- "HH:mm", 24-hour, zero-padded. Times are wall-clock facts about a shop, stored as text on
-- purpose (see the model docblock) — which means the format is application discipline unless it is
-- checked here. NULL is allowed: a closed day has no hours.
ALTER TABLE "opening_hours" ADD CONSTRAINT "opening_hours_time_format" CHECK (
  ("opens_at"  IS NULL OR "opens_at"  ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$')
  AND ("closes_at" IS NULL OR "closes_at" ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$')
);

-- מע"מ as basis points. 0-10000 covers 0% to 100%; anything outside it is a units mistake
-- (someone storing 17 or 0.17 instead of 1700), which is precisely the bug this catches.
ALTER TABLE "tax_settings" ADD CONSTRAINT "tax_settings_vat_range" CHECK (
  "vat_rate_basis_points" IS NULL
  OR ("vat_rate_basis_points" >= 0 AND "vat_rate_basis_points" <= 10000)
);

-- Analytics counters are counts.
ALTER TABLE "analytics_daily" ADD CONSTRAINT "analytics_daily_counts_nonneg" CHECK (
  "visitors" >= 0 AND "pageviews" >= 0 AND "product_views" >= 0 AND "whatsapp_clicks" >= 0
  AND "add_to_carts" >= 0 AND "checkout_starts" >= 0 AND "orders" >= 0
);

ALTER TABLE "section_dwell_daily" ADD CONSTRAINT "section_dwell_daily_counts_nonneg" CHECK (
  "views" >= 0 AND "total_dwell_ms" >= 0
);

-- A day's zero-result searches cannot exceed that day's searches. The rollup computes both from
-- the same rows, so a violation here means the rollup's arithmetic is wrong — which is a bug worth
-- failing loudly rather than a number worth displaying.
ALTER TABLE "search_query_daily" ADD CONSTRAINT "search_query_daily_counts_sane" CHECK (
  "searches" >= 0 AND "zero_results" >= 0 AND "zero_results" <= "searches"
);

-- Raw analytics rows carry no free-text identity. `dwell_ms` is clamped in the ingest route to
-- `platform_settings.analytics_max_dwell_ms`; this is the floor half of that clamp, and the reason
-- it is a CHECK is that a negative duration is not a small error, it is a sign the client's clock
-- was trusted.
ALTER TABLE "analytics_events" ADD CONSTRAINT "analytics_events_dwell_sane" CHECK (
  ("dwell_ms" IS NULL OR "dwell_ms" >= 0)
  AND ("result_count" IS NULL OR "result_count" >= 0)
);

-- A carrier key is a stable machine identifier, lowercase, and never Arabic — `name` is where the
-- Arabic display name lives. Same discipline as `Category.key` and `Plan.key`.
ALTER TABLE "carriers" ADD CONSTRAINT "carriers_key_slug_shape"
  CHECK ("key" ~ '^[a-z0-9][a-z0-9_-]*$');

-- The town match key is produced ONLY by `normaliseTownName()` (src/server/delivery/towns.ts),
-- which lowercases nothing (Arabic has no case) but does strip the ال prefix, fold أإآا to ا,
-- ة to ه, ى to ي, remove tatweel, and collapse whitespace. What this CHECK can enforce cheaply is
-- the part that is always true of its output regardless of script: no leading or trailing
-- whitespace, and never empty. A blank normalised key would match every unparseable address.
ALTER TABLE "delivery_zone_towns" ADD CONSTRAINT "delivery_zone_towns_normalised_trimmed" CHECK (
  length("normalised") > 0 AND "normalised" = btrim("normalised")
);

-- Platform-wide Phase 9 constants stay sane.
ALTER TABLE "platform_settings" ADD CONSTRAINT "platform_settings_phase9_nonneg" CHECK (
  "low_stock_threshold_default" >= 0
  AND "analytics_raw_retention_days" >= 1
  AND "analytics_max_dwell_ms" >= 1000
);
