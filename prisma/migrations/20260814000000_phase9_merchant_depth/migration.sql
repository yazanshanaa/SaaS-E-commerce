-- -----------------------------------------------------------------------------
-- 1. Row-level security on the fifteen new tenant-owned tables — the exact generic template from
--    prisma/migrations/20260809000100_rls_roles_and_guards/migration.sql, scoped to just these,
--    because that migration's own DO block already ran for every table that existed before it.
--
--    Invariant 1: isolation is enforced TWICE. The Prisma client extension sets the GUCs; this is
--    the layer that still refuses when the extension is bypassed, forgotten, or a raw query slips
--    through. `tests/integration/isolation.test.ts` proves it with the extension disabled, and
--    Phase 9 adds every table below to that proof.
--
--    `analytics_events` is in this list even though only the beacon route writes it and only the
--    rollup job reads it. A table nobody is "supposed to" read cross-tenant is exactly the table a
--    future reporting query reads cross-tenant by accident.
-- -----------------------------------------------------------------------------
DO $$
DECLARE
  t text;
  tenant_tables text[] := ARRAY[
    'product_variants',
    'size_guide_entries',
    'banners',
    'trust_badges',
    'opening_hours',
    'store_stats',
    'customers',
    'delivery_zones',
    'delivery_zone_towns',
    'tenant_carriers',
    'tax_settings',
    'analytics_events',
    'analytics_daily',
    'section_dwell_daily',
    'search_query_daily'
  ];
BEGIN
  FOREACH t IN ARRAY tenant_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);

    -- The generic template. Identical USING and WITH CHECK: a tenant may not read another
    -- tenant's row, and may not write one either.
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I
        FOR ALL TO app_web
        USING (
          tenant_id = current_setting('app.tenant_id', true)
          OR current_setting('app.actor_role', true) = 'super_admin'
        )
        WITH CHECK (
          tenant_id = current_setting('app.tenant_id', true)
          OR current_setting('app.actor_role', true) = 'super_admin'
        )
    $p$, t);

    -- app_system reads ids to fan out. It never writes a tenant-owned table — enforced by the
    -- GRANTs below, not merely by this policy.
    EXECUTE format($p$
      CREATE POLICY system_read ON %I FOR SELECT TO app_system USING (true)
    $p$, t);

    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO app_web', t);
    EXECUTE format('GRANT SELECT ON %I TO app_system', t);
  END LOOP;
END
$$;

-- -----------------------------------------------------------------------------
-- 2. The analytics rollup is the FIRST out-of-request job that must WRITE tenant-owned rows.
--
--    Every earlier job either only read (`lifecycle-sweep` fanning out ids) or wrote through
--    `withTenantTxn` as app_web. The rollup does the latter — it runs per tenant, inside
--    withTenantTxn, as app_web with `app.tenant_id` set — so the GRANTs above are exactly right and
--    app_system deliberately keeps SELECT only. Stated here because the temptation to "just let
--    app_system write the rollups, it's only counters" would hand a cross-tenant write path to the
--    one role whose read policy is `USING (true)`. Do not.
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- 3. carriers / carrier_rates — GLOBAL (prisma/GLOBAL_TABLES.md), following the exact shape
--    migration 0001 gave `plans` and `plan_features`: a platform catalogue is readable by every
--    web request (a merchant must see the carrier they were assigned) and writable by app_web,
--    with the super-admin-only route as the actual enforcement — src/server/delivery/carriers.ts.
--    app_system gets SELECT so a future report can count assignments without a write path.
--
--    No RLS: there is no tenant_id for the generic template to key on, and unlike `users` or
--    `sessions` there is nothing personal here to protect. A delivery company's public price list
--    is not a secret.
-- -----------------------------------------------------------------------------
GRANT SELECT ON "carriers", "carrier_rates" TO app_web, app_system;
GRANT INSERT, UPDATE, DELETE ON "carriers", "carrier_rates" TO app_web;

